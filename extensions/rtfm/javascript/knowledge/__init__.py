def normalise_symbol(query: str) -> str:
    """Normalise `'iterator'`, `'@@iterator'`, or `'Symbol.iterator'` to a lookup key."""
    cleaned = query.strip().strip("`").removesuffix("()").strip()
    if cleaned.startswith("@@"):
        cleaned = f"Symbol.{cleaned[2:]}"
    elif not cleaned.casefold().startswith("symbol."):
        cleaned = f"Symbol.{cleaned}"
    return cleaned


def lookup_symbol(query: str) -> SymbolInfo | None:
    """Find a :class:`SymbolInfo` by exact name, normalised `Symbol.<name>`, or alias."""
    raw = query.strip().strip("`").removesuffix("()").casefold()
    norm = normalise_symbol(query).casefold()
    for key, info in SYMBOLS_DB.items():
        if key.casefold() in {raw, norm}:
            return info
        if any(alias.casefold() in {raw, norm} for alias in info.aliases):
            return info
    return None


