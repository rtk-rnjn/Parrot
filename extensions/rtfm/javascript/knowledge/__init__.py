from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class BuiltinInfo:
    name: str
    category: str
    signature: str | None
    summary: str
    methods: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class ErrorInfo:
    name: str
    category: str
    summary: str
    causes: tuple[str, ...]
    fix: str
    example: str
    anchor: str | None = None


@dataclass(frozen=True, slots=True)
class OperatorInfo:
    symbol: str
    name: str
    category: str
    summary: str
    precedence: str
    dunder: str
    operator_func: str | None
    example: str
    anchor: str
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class StdlibMeta:
    name: str
    category: str
    summary: str
    highlights: tuple[str, ...]
    example: str
    source_path: str | None = None


@dataclass(frozen=True, slots=True)
class ComplexityInfo:
    key: str
    title: str
    category: str
    summary: str
    best: str
    average: str
    worst: str
    space: str
    notes: tuple[str, ...]
    example: str
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class KeywordInfo:
    name: str
    summary: str
    example: str
    doc: str
    since: str | None = None


@dataclass(frozen=True, slots=True)
class SymbolInfo:
    name: str
    group: str
    summary: str
    signature: str
    called_by: str
    backs: str | None
    example: str
    doc: str
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class GotchaInfo:
    key: str
    title: str
    summary: str
    bad: str
    good: str
    why: str
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class IdiomInfo:
    key: str
    title: str
    summary: str
    example: str
    since: str | None = None
    notes: str | None = None
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class TypingInfo:
    key: str
    title: str
    summary: str
    example: str
    doc: str
    since: str | None = None
    aliases: tuple[str, ...] = ()


